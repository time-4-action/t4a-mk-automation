const postgres = require("postgres");

// The app's Postgres (t4a: the shared Postgres 18, database `mk-automation`). Replaces the
// SQLite file patrik.db; src/sqliteImport.js copies an old file in once, at boot.
//
// The API keeps returning rows exactly as it did with SQLite, so t4a-admin and the
// dashboards in public/ need no change:
// - timestamps come back as "YYYY-MM-DD HH:MM:SS" (UTC), SQLite's CURRENT_TIMESTAMP format;
// - flags stay integers 0/1, ids and counts are plain numbers (integer, not bigint);
// - sync_runs.details stays a JSON string (text).
const url = process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL is not set (see .env.example)");

const sql = postgres(url, {
    max: 5,
    idle_timeout: 60,
    // Session time zone UTC, so timestamptz values are written and read as UTC.
    connection: { TimeZone: "UTC", application_name: "t4a-mk-automation" },
    onnotice: () => {},
    types: {
        // timestamptz (oid 1184) arrives as "2026-11-07 10:00:00.123456+00"; keep the seconds.
        sqliteTimestamp: {
            to: 1184,
            from: [1184],
            serialize: (x) => (x instanceof Date ? x.toISOString() : x),
            parse: (x) => x.slice(0, 19)
        }
    }
});

// Schema migrations, applied in order at boot. Append new ones; never edit one that has shipped.
// Column names, types and defaults mirror the SQLite tables (CREATE TABLE in the old index.js).
const MIGRATIONS = [
    /* 1: initial schema, moved from SQLite */ `
    CREATE TABLE warehouse_sync_log (
        id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        link       text,
        sync_name  text DEFAULT 'T4A',
        created_at timestamptz DEFAULT now()
    );

    CREATE TABLE product_sync_log (
        id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sync_name        text,
        status           text,
        source_warehouse text,
        target_warehouse text,
        created_at       timestamptz DEFAULT now()
    );

    CREATE TABLE customer_sync_log (
        id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sync_name      text,
        source_company text,
        target_company text,
        created        integer,
        updated        integer,
        created_at     timestamptz DEFAULT now()
    );

    CREATE TABLE pricelist_sync_log (
        id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sync_name      text,
        source_company text,
        target_company text,
        added          integer,
        updated        integer,
        created_at     timestamptz DEFAULT now()
    );

    -- Source → target price-list pairs, entered by a human.
    --
    -- This table is the whole safety mechanism of the pricelist sync. A price list's
    -- count_code is a per-company counter and does NOT identify the same list across the two
    -- companies: live data has T4A 7 = "PP GOLD 2026" against CREAGLOBE 7 = "PP BRONZE 2026".
    -- Syncing by code would write GOLD prices into BRONZE, so nothing is ever synced that is
    -- not explicitly paired here. Identity is (sales_purchase, count_code): Metakocka numbers
    -- sales and purchase lists separately, so the code alone is ambiguous even within one
    -- company.
    CREATE TABLE pricelist_map (
        id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source_code           text NOT NULL,             -- T4A price list count_code
        source_sales_purchase text NOT NULL DEFAULT 'sales',
        source_title          text,                      -- snapshot, for display when a list goes empty
        target_code           text NOT NULL,             -- CREAGLOBE price list count_code
        target_sales_purchase text NOT NULL DEFAULT 'sales',
        target_title          text,
        enabled               integer NOT NULL DEFAULT 1,
        allow_unseen_target   integer NOT NULL DEFAULT 0,
        -- Safety rail: refuse any single price move larger than this percentage and report it
        -- instead of writing. NULL = no limit. Exists because two mapped lists can hold
        -- different KINDS of number (live data had CREAGLOBE storing gross where T4A stores
        -- net), and a blind sync would then rewrite a whole catalogue by the VAT factor.
        max_change_pct        double precision,
        -- Unused: VAT is mirrored 1:1 from T4A. Kept so copied SQLite rows fit unchanged.
        default_tax           text,
        created_at            timestamptz DEFAULT now(),
        updated_at            timestamptz DEFAULT now()
    );
    -- One source list may only be mapped once: two mappings for the same source would race
    -- each other writing different prices onto the same products.
    CREATE UNIQUE INDEX pricelist_map_source_unique
        ON pricelist_map (source_sales_purchase, source_code);

    -- Unified run history for the admin "Automation" page: one row per sync run (scheduled or
    -- manual) with its outcome, duration and item count. node-cron exposes no last-run/next-run
    -- info, so the app tracks it here.
    CREATE TABLE sync_runs (
        id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        type        text,     -- 'warehouse' | 'products' | 'customers' | 'pricelists'
        trigger     text,     -- 'manual' | 'schedule'
        status      text,     -- 'running' | 'ok' | 'error'
        item_count  integer,
        error       text,
        details     text,     -- JSON string
        started_at  timestamptz DEFAULT now(),
        finished_at timestamptz,
        duration_ms integer
    );
    CREATE INDEX sync_runs_type_id_idx ON sync_runs (type, id DESC);
    `
];

/** Applies pending migrations in one transaction, under a lock so two processes can't race. */
async function migrate() {
    await sql.begin(async (tx) => {
        await tx`SELECT pg_advisory_xact_lock(hashtext('t4a-mk-automation:migrate'))`;
        await tx`CREATE TABLE IF NOT EXISTS schema_migrations (
            version    integer PRIMARY KEY,
            applied_at timestamptz NOT NULL DEFAULT now()
        )`;
        const [{ v }] = await tx`SELECT COALESCE(MAX(version), 0)::int AS v FROM schema_migrations`;
        for (let i = v; i < MIGRATIONS.length; i++) {
            await tx.unsafe(MIGRATIONS[i]);
            await tx`INSERT INTO schema_migrations (version) VALUES (${i + 1})`;
            console.log(`🗄️  database migration ${i + 1} applied`);
        }
    });
}

module.exports = { sql, migrate, MIGRATIONS };
